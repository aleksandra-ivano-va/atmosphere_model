double Atmosphere::M_high(double h) const
{
    if (h <= 97000.0)
        return 28.82 + 0.158 * sqrt(1 - 7.5 * pow(10, -8) * pow(h - 94000, 2)) - 2.479 * pow(10, -4) * sqrt(97000 - h);
    else if (h <= 97500.0) 
        return 28.91 - 0.00012 * (h - 97000.0);
    else 
        return 28.85 - 0.0001511 * (h - 97500.0);
}

double Atmosphere::find_H(double h) const 
{
    return r * h / (r + h);
}

double Atmosphere::find_h(double H) const 
{
    return r * H / (r - H);
}

AtmosParams Atmosphere::getParams(double h) const {
    AtmosParams p;
    double H = find_H(h);
    p.g = g0 * pow(r / (r + h), 2);
    p.M = Mc;
    
    // Поиск индекса в таблице высот
    int idx = 0;
    for (int i = 0; i < 21; ++i) {
        if (H >= H0[i] && H < H0[i + 1]) {
            idx = i;
            break;
        }
    }

    if (h < 94000.0) {
        p.T = T0[idx] + b[idx] * (H - H0[idx]);
        if (bm[idx] != 0.0)
            p.P = pow(10, log10(P0[idx]) - g0 / (bm[idx] * R) * log10((Tm0[idx] + bm[idx] * (H - H0[idx])) / Tm0[idx]));
        else
            p.P = pow(10, log10(P0[idx]) - 0.434294 / (R * p.T) * g0 * (H - H0[idx]));
        
        p.ro = p.P / (R * p.T);
        p.a = sqrt(x * R * p.T);
        p.n = 7.243611E+22 * p.P / p.T; 
        if (h < 90000.0)
            p.nu= beta_S * sqrt(pow(p.T, 3)) / (p.T + S);
        else p.nu = 0.0;
    } 
    else if (h < 120000.0) {
        double Tm = Tm0[idx] + bm[idx] * (H - H0[idx]);
        p.M = M_high(h);
        p.T = Tm * p.M / Mc;
        
        if (bm[idx] != 0.0)
            p.P = pow(10, log10(P0[idx]) - g0 / (bm[idx] * R) * log10(Tm / Tm0[idx]));
        else
            p.P = pow(10, log10(P0[idx]) - 0.434294 / (R * p.T) * g0 * (H - H0[idx]));
            
        p.ro = p.P / (R * p.T);
        p.a = sqrt(x * R_zv * p.T / p.M);
        p.n = 7.243611E+22 * p.P / p.T; 
        p.nu = 0.0;
    } 
    else {
        // Логика для высот > 120 км
        for (int ii = 0; ii < 9; ii++) {
            if (h >= h_hi0[ii] && h < h_hi0[ii + 1]) {
                double n = (A[ii][0] + A[ii][1] * h + A[ii][2] * pow(h, 2) + A[ii][3] * pow(h, 3) + A[ii][4] * pow(h, 4)) * pow(10, m[ii]);
                double Tm = T0[idx] + b[idx] * (h - h_hi0[ii]);
                
                for (int iii = 0; iii < 6; iii++) {
                    if (h >= h_hi00[iii] && h < h_hi00[iii + 1])
                        p.M = B[iii][0] + B[iii][1] * h + B[iii][2] * pow(h, 2) + B[iii][3] * pow(h, 3);
                }
                
                p.T = Tm * p.M / Mc;
                p.P = n * R_zv * p.T / Na;
                p.ro = p.P * p.M / (R_zv * p.T);
                p.a = sqrt(x * R_zv * p.T / p.M);
                p.n = n; 
                p.nu = 0.0;
                break;
            }
        }
    }

    return p;
}

